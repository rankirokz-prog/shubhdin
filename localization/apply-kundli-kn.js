// SHUBH DIN — apply-kundli-kn.js : applies report-strings.kn.json into report-content.js
// Dedicated Kannada pipeline. Sibling of apply-kundli.js (hi) — does NOT modify it.
// Same key format: kundli.<path>.<en|t_en|xxxEn>  ->  <kn|t_kn|xxxKn>
// Language Bible rule 3: JSON is the editable source; report-content.js is generated.
const fs = require('fs');
global.window = global;
require('./report-content.js');
const C = global.SD_CONTENT;
if (!C) { console.error('SD_CONTENT not found after loading report-content.js'); process.exit(1); }

const M = JSON.parse(fs.readFileSync('report-strings.kn.json', 'utf8'));
let n = 0;
const bad = [];

for (const key of Object.keys(M)) {
  const m = key.match(/^kundli\.(.+)\.(en|t_en|\w+En)$/);
  if (!m) { bad.push(key + ' (unparseable)'); continue; }
  // EN-bearing field -> Kannada field
  const tf = m[2] === 'en' ? 'kn'
           : m[2] === 't_en' ? 't_kn'
           : m[2].slice(0, -2) + 'Kn';
  let o = C, ok = true;
  for (const part of m[1].split('.')) {
    const a = part.match(/^(\w+)\[(\d+)\]$/);
    o = a ? (o && o[a[1]] && o[a[1]][+a[2]]) : (o && o[part]);
    if (o == null) { ok = false; break; }
  }
  if (!ok) { bad.push(key + ' (path not found)'); continue; }
  o[tf] = M[key];
  n++;
}

console.log('applied:', n);
if (bad.length) {
  console.error('✗ PROBLEM KEYS:', bad.length);
  bad.slice(0, 8).forEach(b => console.error('   •', b));
  process.exit(1);
}

const header =
  '// SHUBH DIN — free Kundli content (multi-language)\n' +
  '// GENERATED by localization pipeline. DO NOT HAND-EDIT (Language Bible rule 3).\n' +
  '// Sources: report-strings.hi.json / report-strings.te.json / report-strings.kn.json\n' +
  '// Regenerated: ' + new Date().toISOString() + '\n';
fs.writeFileSync('report-content.js',
  header + '(function(g){g.SD_CONTENT=' + JSON.stringify(C) + ';})(typeof window!==\'undefined\'?window:global);\n',
  'utf8');
console.log('✓ report-content.js regenerated');
